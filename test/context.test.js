test("glossary candidates are lowercase and comma separated", () => {
  const body = section(doc, "Glossary candidates").trim();
  const last = body.split("\n").filter(Boolean).pop();
  assert.match(last, /revenue/);
  assert.match(last, /users/);
  assert.equal(last, last.toLowerCase());
  const terms = last.split(", ");
  assert.ok(terms.length <= 30, `got ${terms.length} terms`);
  assert.equal(new Set(terms).size, terms.length, "terms are distinct");
  assert.ok(!terms.includes("month"), "time grains are not business vocabulary");
  assert.ok(!terms.includes("card"), "Metabase's own nouns are not business vocabulary");
  assert.ok(terms.includes("churn"), "a business term counts even with one mention");
});

