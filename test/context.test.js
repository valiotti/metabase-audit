test("style rules: no dashes, no undefined, no NaN, tables have separators", () => {
  assert.ok(!doc.includes("\u2014"), "em dash");
  assert.ok(!doc.includes("\u2013"), "en dash");
  assert.ok(!/\bundefined\b/.test(doc), "undefined");
  assert.ok(!/\bNaN\b/.test(doc), "NaN");
  for (const line of doc.split("\n")) {
    if (line.startsWith("| ") && /\| (Dashboard|Owner) \|/.test(line)) {
      const next = doc.split("\n")[doc.split("\n").indexOf(line) + 1];
      assert.match(next, /^\| ---/, `header without separator: ${line}`);
    }
  }
});

