test("key findings carry between 4 and 8 numbered bullets", () => {
  const body = section(doc, "Key findings");
  const bullets = body.split("\n").filter((l) => l.startsWith("- "));
  assert.ok(bullets.length >= 4 && bullets.length <= 8, `got ${bullets.length} bullets`);
  for (const bullet of bullets) assert.match(bullet, /\d/, `no number in: ${bullet}`);
  assert.match(body, /C\+/);
  assert.match(body, /2 duplicate groups/);
  // The verb agrees with the leading count, not with the trailing noun.
  assert.match(body, /- 1 of 4 tables is never read by a saved question\./);
  assert.match(body, /- 5 of 9 active questions carry no description\./);
  assert.match(body, /- 2 of 3 dashboards carry a broken or a stale card\./);
});

