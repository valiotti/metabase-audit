test("trusted queries truncate long SQL", () => {
  const longSql = Array.from({ length: 80 }, (_, i) => `SELECT ${i} FROM orders`).join("\n");
  const patched = {
    ...snapshot,
    cards: snapshot.cards.map((c) => (c.id === 1 ? { ...c, sql: longSql } : c)),
  };
  const out = renderContext(patched, findings, { now: NOW, topQueries: 1 });
  assert.match(out, /-- truncated/);
  assert.ok(!out.includes("SELECT 70 FROM orders"), "lines past the cap are dropped");
});

