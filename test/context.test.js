import test from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

import { analyze } from "../src/analyze/index.js";
import { loadSnapshotFile } from "../src/snapshot.js";
import { renderContext } from "../src/context.js";

const fixturePath = fileURLToPath(new URL("./fixtures/snapshot.small.json", import.meta.url));
const NOW = new Date("2026-09-16T00:00:00Z");

const snapshot = await loadSnapshotFile(fixturePath);
const findings = analyze(snapshot, { now: NOW });
const doc = renderContext(snapshot, findings, { now: NOW });

/** Body of one `## ` section, without its heading. */
function section(text, title) {
  const parts = text.split(/^## /m);
  const found = parts.find((p) => p.startsWith(`${title}\n`));
  assert.ok(found, `section "${title}" is missing`);
  return found.slice(title.length);
}

function countOccurrences(haystack, needle) {
  return haystack.split(needle).length - 1;
}

test("header names the instance and carries the preamble", () => {
  assert.ok(doc.startsWith("# Data context: Acme\n"));
  assert.match(doc, /This file is generated by metabase-audit\./);
  assert.match(doc, /Instance: https:\/\/metabase\.acme\.test/);
  assert.match(doc, /v0\.62\.3/);
  assert.match(doc, /Generated: 2026-09-16/);
});

test("sections appear once, in the documented order", () => {
  const order = [
    "## Instance overview",
    "## Data model",
    "## Relationships",
    "## Dashboards",
    "## Team and ownership",
    "## Key findings",
    "## Trusted queries",
    "## Glossary candidates",
    "## Notes for the reader",
  ];
  let cursor = -1;
  for (const heading of order) {
    const at = doc.indexOf(`\n${heading}\n`);
    assert.ok(at > cursor, `${heading} is missing or out of order`);
    assert.equal(countOccurrences(doc, `\n${heading}\n`), 1, `${heading} appears more than once`);
    cursor = at;
  }
});

